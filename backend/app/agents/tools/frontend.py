@lru_cache(maxsize=1)
def _project_tokens() -> dict[str, Any]:
    """This project's own theme tokens, read from its tailwind config.

    Parsed rather than restated, so a token renamed in the config does not
    leave the agent recommending a class that no longer resolves. It is a
    tolerant regex scrape of a TypeScript object, not a parse — if the file
    moves or changes shape, the tool reports that it could not read it instead
    of returning a stale list.
    """
    if not _TAILWIND_CONFIG.exists():
        return {"available": False, "reason": f"{_TAILWIND_CONFIG.name} not found."}

    try:
        source = _TAILWIND_CONFIG.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        return {"available": False, "reason": str(exc)}

    def _keys(block_name: str) -> list[str]:
        match = re.search(rf"{block_name}:\s*\{{", source)
        if not match:
            return []
        # Walk the braces so a nested object (`ink: {{ … }}`) is consumed whole
        # rather than terminating the block at its first `}`.
        depth, start = 0, match.end() - 1
        for i in range(start, len(source)):
            if source[i] == "{":
                depth += 1
            elif source[i] == "}":
                depth -= 1
                if depth == 0:
                    body = source[start + 1 : i]
                    break
        else:
            return []
        out: list[str] = []
        depth = 0
        for line in body.splitlines():
            stripped = line.strip()
            if depth == 0:
                key = re.match(r'^["\']?([\w-]+)["\']?\s*:', stripped)
                if key and key.group(1) != "DEFAULT":
                    out.append(key.group(1))
            depth += stripped.count("{") - stripped.count("}")
        return out

    colours = _keys("colors")
    return {
        "available": True,
        "source": "frontend/tailwind.config.ts",
        "colours": colours,
        "usage": {
            "background": [f"bg-{c}" for c in colours[:14]],
            "text": ["text-ink", "text-ink-muted", "text-ink-faint", "text-accent", "text-warn", "text-del", "text-add"],
            "border": ["border-line", "border-line-strong", "border-accent-line"],
        },
        "radius": [f"rounded-{r}" for r in _keys("borderRadius")],
        "font_size": [f"text-{s}" for s in _keys("fontSize")],
        "shadow": [f"shadow-{s}" for s in _keys("boxShadow")],
        "animation": [f"animate-{a}" for a in _keys("animation")],
        "note": (
            "These are THIS project's tokens and follow the active section's "
            "accent automatically. Prefer them over raw palette classes when "
            "the component is meant to live inside this app. `accent` resolves "
            "from a CSS variable set by `data-section`, so the same markup "
            "takes on the right colour in Chat, Learn, Code or Agents."
        ),
    }


#: Enough of Tailwind's grammar to tell a real class from a plausible one
#: without shipping the framework's full class list. Anything matching here is
#: reported "plausible"; anything in the reference above is reported "known".
_CLASS_SHAPE = re.compile(
    r"^(?:(?:sm|md|lg|xl|2xl|hover|focus|focus-visible|focus-within|active|"
    r"disabled|group-hover|group-focus|peer-checked|dark|motion-safe|"
    r"motion-reduce|first|last|odd|even|print):)*"
    r"-?[a-z][a-z0-9]*(?:-[a-z0-9.]+)*(?:\/\d{1,3})?(?:\[[^\]]+\])?$"
)


def _flatten_reference() -> set[str]:
    out: set[str] = set()
    for group in TAILWIND_REFERENCE.values():
        for value in group.values():
            if isinstance(value, list):
                out.update(v.split(" ")[0] for v in value)
    tokens = _project_tokens()
    if tokens.get("available"):
        for key in ("radius", "font_size", "shadow", "animation", "border", "text", "background"):
            value = tokens.get(key) or (tokens.get("usage") or {}).get(key)
            if isinstance(value, list):
                out.update(value)
    return out


async def lookup_tailwind(ctx: ToolContext, args: dict) -> ToolResult:
    """Look up utility families, and validate specific classes."""
    query = (args.get("query") or "").strip().lower()
    classes = args.get("classes") or []
    if isinstance(classes, str):
        classes = classes.split()

    payload: dict[str, Any] = {}

    if classes:
        known = _flatten_reference()
        checked = []
        for raw in classes[:60]:
            name = str(raw).strip()
            if not name:
                continue
            base = name.split(":")[-1]
            if name in known or base in known:
                verdict = "known"
            elif _CLASS_SHAPE.match(name):
                verdict = "plausible"
            else:
                verdict = "malformed"
            checked.append({"class": name, "verdict": verdict})
        payload["validated"] = checked
        payload["validation_note"] = (
            "`known` is in this reference. `plausible` is well-formed Tailwind "
            "grammar that this reference does not enumerate — most of the "
            "spacing and colour scales fall here, and they are usually fine. "
            "`malformed` cannot be a Tailwind class at all; replace it."
        )

    if query:
        matches = {
            group: {
                key: value
                for key, value in entries.items()
                if query in key.lower()
                or (isinstance(value, list) and any(query in v.lower() for v in value))
                or (isinstance(value, str) and query in value.lower())
            }
            for group, entries in TAILWIND_REFERENCE.items()
        }
        payload["reference"] = {g: e for g, e in matches.items() if e} or {
            "note": f"Nothing matched `{query}`. Omit `query` to see every family."
        }
    elif not classes:
        payload["reference"] = TAILWIND_REFERENCE

    payload["project_tokens"] = _project_tokens()
    return ToolResult(output=as_json(payload, limit=16_000), meta={"query": query})


