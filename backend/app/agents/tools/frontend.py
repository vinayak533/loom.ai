@lru_cache(maxsize=1)
def _icons() -> dict[str, Any]:
    path = _DATA / "lucide_icons.json"
    if not path.exists():
        return {"version": "unknown", "icons": []}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        log.warning("Could not read the Lucide icon list", exc_info=True)
        return {"version": "unknown", "icons": []}


def icon_exists(name: str) -> bool:
    return name in set(_icons().get("icons") or [])


