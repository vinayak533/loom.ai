async def lookup_lucide_icons(ctx: ToolContext, args: dict) -> ToolResult:
    """Find valid icon names for a concept, or validate the ones you picked."""
    data = _icons()
    all_icons: list[str] = list(data.get("icons") or [])
    if not all_icons:
        return ToolResult(
            "The Lucide icon list has not been generated. Run "
            "`python scripts/generate_lucide_icons.py` in backend/. Do not "
            "guess icon names in the meantime — say you could not verify them.",
            success=False,
        )

    lookup = set(all_icons)
    query = (args.get("query") or "").strip()
    names = args.get("names") or []
    if isinstance(names, str):
        names = names.split()

    payload: dict[str, Any] = {"lucide_version": data.get("version")}

    if names:
        payload["validated"] = [
            {"name": str(n), "exists": str(n) in lookup} for n in names[:40]
        ]
        missing = [v["name"] for v in payload["validated"] if not v["exists"]]
        if missing:
            payload["replace"] = {
                name: _suggest(name, all_icons, lookup)[:5] for name in missing
            }

    if query:
        payload["matches"] = _suggest(query, all_icons, lookup)[:30]
        if not payload["matches"]:
            payload["matches_note"] = (
                f"Nothing matched `{query}`. Lucide names are literal — try the "
                "object rather than the action ('Trash2' not 'delete')."
            )

    if not names and not query:
        payload["total"] = len(all_icons)
        payload["note"] = "Pass `query` to search or `names` to validate."

    return ToolResult(output=as_json(payload), meta={"count": len(all_icons)})


def _suggest(term: str, all_icons: list[str], lookup: set[str]) -> list[str]:
    term = term.strip()
    lowered = term.lower()
    out: list[str] = []

    for concept, icons in _SYNONYMS.items():
        if lowered in concept or concept in lowered:
            out.extend(i for i in icons if i in lookup)

    # Substring on the CamelCase name, then on its words, so "arrow up" finds
    # ArrowUp even though the name has no space in it.
    squashed = re.sub(r"[^a-z0-9]", "", lowered)
    for name in all_icons:
        flat = name.lower()
        if lowered and (lowered in flat or (squashed and squashed in flat)):
            out.append(name)

    seen: set[str] = set()
    return [i for i in out if not (i in seen or seen.add(i))]


